-- 1. TABLA: testimonials (Capítulo IV · Resonancias & Huellas)
CREATE TABLE IF NOT EXISTS public.testimonials (
  id TEXT PRIMARY KEY,
  author TEXT NOT NULL,
  role TEXT DEFAULT 'Consultante',
  location TEXT DEFAULT 'Consulta Online',
  session_type TEXT DEFAULT '01 · TAROT',
  archetype TEXT DEFAULT 'Resonancia Simbólica',
  year TEXT DEFAULT '2026',
  gender TEXT DEFAULT 'female' CHECK (gender IN ('female', 'male', 'couple')),
  quote TEXT NOT NULL,
  avatar_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABLA: essays (Capítulo V · Ensayos & Apuntes - Notas Editoriales completas)
CREATE TABLE IF NOT EXISTS public.essays (
  id TEXT PRIMARY KEY,
  category TEXT NOT NULL DEFAULT 'Tarot',
  number TEXT NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT,
  read_time TEXT DEFAULT '5 min',
  date TEXT DEFAULT 'Bitácora 2026',
  excerpt TEXT,
  full_essay JSONB NOT NULL DEFAULT '[]'::jsonb,
  media_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA: essay_notes (Capítulo V · Notas al Margen y Apuntes dentro de cada ensayo)
CREATE TABLE IF NOT EXISTS public.essay_notes (
  id TEXT PRIMARY KEY,
  essay_id TEXT NOT NULL,
  author TEXT DEFAULT 'Nota de Lectura',
  note TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABLA: bookings (Reservas de Consultas enviadas a dalekavideos@gmail.com)
CREATE TABLE IF NOT EXISTS public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_type TEXT NOT NULL,
  client_name TEXT NOT NULL,
  client_email TEXT NOT NULL,
  preferred_date TEXT,
  preferred_time TEXT,
  notes TEXT,
  recipient_email TEXT DEFAULT 'dalekavideos@gmail.com',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- POLÍTICAS DE SEGURIDAD (ROW LEVEL SECURITY - RLS) PARA LECTURA E INSERCIÓN
-- ============================================================================

ALTER TABLE public.testimonials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.essays ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.essay_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

